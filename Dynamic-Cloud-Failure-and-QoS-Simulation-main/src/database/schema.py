"""Database schema definitions and DDL scripts for Phase 9 SQLite persistence.

Defines schemas for service state persistence, failure events, monitoring history,
reselection audit trails, manual override transitions, and schema versioning.
"""

from __future__ import annotations
from typing import List

CURRENT_SCHEMA_VERSION = 1

# Table: schema_version
CREATE_SCHEMA_VERSION_TABLE = """
CREATE TABLE IF NOT EXISTS schema_version (
    version INTEGER PRIMARY KEY,
    applied_at TEXT NOT NULL,
    description TEXT NOT NULL
);
"""

# Table: service_states
# Stores real-time candidate cloud service states and baseline references.
CREATE_SERVICE_STATES_TABLE = """
CREATE TABLE IF NOT EXISTS service_states (
    service_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    latency REAL NOT NULL,
    cost REAL NOT NULL,
    availability REAL NOT NULL,
    reliability REAL NOT NULL,
    operational_status TEXT NOT NULL,
    baseline_latency REAL NOT NULL,
    baseline_cost REAL NOT NULL,
    baseline_availability REAL NOT NULL,
    baseline_reliability REAL NOT NULL,
    baseline_operational_status TEXT NOT NULL,
    last_updated TEXT NOT NULL
);
"""

# Table: simulation_events
# Historical log of failure injections, outages, and restorations.
CREATE_SIMULATION_EVENTS_TABLE = """
CREATE TABLE IF NOT EXISTS simulation_events (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    action TEXT NOT NULL,
    service_id TEXT NOT NULL,
    service_name TEXT NOT NULL,
    injected_latency_change REAL DEFAULT 0.0,
    injected_availability_change REAL DEFAULT 0.0,
    previous_state TEXT,
    resulting_state TEXT,
    details TEXT NOT NULL,
    timestamp TEXT NOT NULL,
    epoch_time REAL NOT NULL
);
"""

# Table: monitoring_events
# Detailed event stream generated by the periodic health surveillance engine.
CREATE_MONITORING_EVENTS_TABLE = """
CREATE TABLE IF NOT EXISTS monitoring_events (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sequence_number INTEGER NOT NULL,
    cycle_number INTEGER NOT NULL,
    event_type TEXT NOT NULL,
    service_id TEXT NOT NULL,
    service_name TEXT NOT NULL,
    category TEXT NOT NULL,
    previous_health_state TEXT,
    new_health_state TEXT,
    health_state TEXT,
    sla_compliant INTEGER,
    qos_score REAL,
    reason TEXT NOT NULL,
    timestamp TEXT NOT NULL,
    epoch_time REAL NOT NULL
);
"""

# Table: reselection_records
# Comprehensive audit trail of recommendation and reselection decisions.
CREATE_RESELECTION_RECORDS_TABLE = """
CREATE TABLE IF NOT EXISTS reselection_records (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sequence_number INTEGER NOT NULL,
    timestamp TEXT NOT NULL,
    trigger_event TEXT NOT NULL,
    prev_service_id TEXT,
    prev_service_name TEXT,
    prev_qos_score REAL,
    prev_health_status TEXT,
    new_service_id TEXT NOT NULL,
    new_service_name TEXT NOT NULL,
    new_qos_score REAL NOT NULL,
    new_health_status TEXT NOT NULL,
    runner_up_id TEXT,
    runner_up_name TEXT,
    runner_up_qos_score REAL,
    reselection_reason TEXT NOT NULL,
    detailed_explanation TEXT NOT NULL,
    q_diff REAL,
    lat_diff REAL,
    avail_diff REAL,
    rel_diff REAL,
    cost_diff REAL,
    decision_type TEXT NOT NULL,
    qos_improvement REAL NOT NULL,
    hysteresis_threshold REAL NOT NULL,
    cooldown_active INTEGER NOT NULL,
    operating_mode TEXT NOT NULL
);
"""

# Table: override_events
# Append-only audit record for operating mode and manual override lifecycle events.
CREATE_OVERRIDE_EVENTS_TABLE = """
CREATE TABLE IF NOT EXISTS override_events (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sequence_number INTEGER NOT NULL,
    timestamp TEXT NOT NULL,
    epoch_time REAL NOT NULL,
    event_type TEXT NOT NULL,
    operating_mode TEXT NOT NULL,
    requested_service_id TEXT,
    selected_service_id TEXT,
    category TEXT NOT NULL,
    reason TEXT NOT NULL
);
"""

# Table: history_snapshots
# Full simulation snapshot tracking across discrete evaluation steps.
CREATE_HISTORY_SNAPSHOTS_TABLE = """
CREATE TABLE IF NOT EXISTS history_snapshots (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    step INTEGER NOT NULL,
    timestamp TEXT NOT NULL,
    action TEXT NOT NULL,
    target_service_id TEXT NOT NULL,
    target_service_name TEXT NOT NULL,
    message TEXT NOT NULL,
    services_json TEXT NOT NULL
);
"""

